#!/usr/bin/env node
/**
 * Build an inactive, consolidated SCMS fresh-install SQL baseline from the
 * exact recovered migration archive. This does not connect to or modify
 * Supabase. The output is deliberately outside supabase/migrations.
 */
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ARCHIVE_DIR = path.join(ROOT, "supabase", "recovered-live-migrations");
const OUTPUT_FILE = path.join(ROOT, "supabase", "baseline", "fresh_install.sql");
const EXPECTED_COUNT = 22;

const preamble = `-- GENERATED FILE: DO NOT EDIT BY HAND.
-- Source: supabase/recovered-live-migrations (22 recovered SCMS-Development migrations).
-- Generated by: bun scripts/build-supabase-baseline.mjs
-- Status: INACTIVE / NOT APPROVED FOR DEPLOYMENT until disposable replay tests pass.
--
-- Target: a fresh Supabase project/database only. Never run against SCMS-Development.
-- Supabase Auth schema, auth.uid(), and platform roles are required.
-- Supabase platform event triggers and extension internals are NOT recreated here.

begin;

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;
create extension if not exists btree_gist with schema extensions;

do $scms_baseline_preflight$
begin
  if to_regnamespace('auth') is null
     or to_regclass('auth.users') is null
     or to_regprocedure('auth.uid()') is null then
    raise exception 'SCMS baseline requires auth.users, auth.uid(), and the Supabase Auth schema';
  end if;

  if not exists (select 1 from pg_roles where rolname = 'anon')
     or not exists (select 1 from pg_roles where rolname = 'authenticated')
     or not exists (select 1 from pg_roles where rolname = 'service_role') then
    raise exception 'SCMS baseline requires the Supabase anon, authenticated and service_role roles';
  end if;

  if to_regclass('public.church_settings') is not null
     or to_regclass('public.profiles') is not null
     or to_regclass('public.roles') is not null then
    raise exception 'SCMS baseline requires a fresh database without existing SCMS core tables';
  end if;
end
$scms_baseline_preflight$;

`;

const extensionReplacements = [
  {
    pattern: /create\s+extension\s+if\s+not\s+exists\s+pgcrypto\s*;/i,
    replacement: "-- pgcrypto is installed in the extensions schema by the baseline preamble."
  },
  {
    pattern: /create\s+extension\s+if\s+not\s+exists\s+btree_gist\s*;/i,
    replacement: "-- btree_gist is installed in the extensions schema by the baseline preamble."
  },
  {
    pattern: /alter\s+extension\s+btree_gist\s+set\s+schema\s+extensions\s*;/i,
    replacement: "-- btree_gist is already installed in its final extensions schema."
  }
];

const rlsFunctionRevoke = /revoke\s+execute\s+on\s+function\s+public\.rls_auto_enable\s*\(\s*\)\s+from\s+public\s*,\s*anon\s*,\s*authenticated\s*;/i;

export function composeBaseline(migrations) {
  if (!Array.isArray(migrations) || migrations.length !== EXPECTED_COUNT) {
    throw new Error(`Expected exactly ${EXPECTED_COUNT} recovered migrations; received ${migrations?.length ?? 0}.`);
  }

  const ordered = [...migrations].sort((a, b) => a.name.localeCompare(b.name));
  const bodies = [];

  for (let index = 0; index < ordered.length; index += 1) {
    const migration = ordered[index];
    const match = migration.name.match(/_scms_(\d{3})_/);
    const expectedSequence = String(index + 1).padStart(3, "0");
    if (!match || match[1] !== expectedSequence) {
      throw new Error(`Migration sequence is incomplete or out of order at ${migration.name}; expected SCMS ${expectedSequence}.`);
    }

    let sql = migration.content.trim();
    if (!/^begin\s*;/i.test(sql) || !/commit;\s*$/i.test(sql)) {
      throw new Error(`Migration ${migration.name} must retain its recorded BEGIN/COMMIT transaction boundaries.`);
    }

    sql = sql.replace(/^begin\s*;/i, "").replace(/commit;\s*$/i, "").trim();

    for (const replacement of extensionReplacements) {
      sql = sql.replace(replacement.pattern, replacement.replacement);
    }

    sql = sql.replace(rlsFunctionRevoke, `do $scms_rls_function_hardening$
begin
  if to_regprocedure('public.rls_auto_enable()') is not null then
    execute 'revoke execute on function public.rls_auto_enable() from public, anon, authenticated';
  end if;
end
$scms_rls_function_hardening$;`);

    if (/\bcreate\s+event\s+trigger\b/i.test(sql)) {
      throw new Error(`Platform event-trigger DDL must not be included in ${migration.name}.`);
    }
    if (/\bcreate\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?members\s*\(/i.test(sql)) {
      throw new Error(`Legacy members-table DDL detected in ${migration.name}; canonical SCMS uses profiles.`);
    }

    bodies.push(`-- -----------------------------------------------------------------------------\n-- ${migration.name}\n-- -----------------------------------------------------------------------------\n${sql}`);

    // The recovered archive is immutable evidence of the live migration ledger.
    // Reconcile the known omission only in the inactive fresh-install baseline,
    // immediately after financial_documents is created and before workflows/indexes.
    if (match[1] === "014") {
      bodies.push(`-- -----------------------------------------------------------------------------\n-- Baseline-only reconciliation: complete financial-document currency fields\n-- -----------------------------------------------------------------------------\nalter table public.financial_documents\n  add column exchange_rate_to_base numeric(20,8) not null default 1,\n  add column base_currency_code char(3) not null default 'SLE' references public.currencies(code);\n\nalter table public.financial_documents\n  add constraint financial_documents_exchange_rate_to_base_check\n    check (exchange_rate_to_base > 0),\n  add constraint financial_document_base_rate\n    check (currency_code <> base_currency_code or exchange_rate_to_base = 1);`);
    }
  }

  bodies.push(`-- -----------------------------------------------------------------------------
-- Baseline-only finance safety guard: pending document journals cannot post
-- -----------------------------------------------------------------------------
create or replace function private.prevent_pending_financial_document_journal_posting()
returns trigger
language plpgsql
set search_path = ''
as $
begin
  if new.status = 'posted'
     and new.source_type = 'financial_document_pending' then
    raise exception 'A financial-document journal cannot be posted before approval and linkage';
  end if;
  return new;
end;
$;

create trigger trg_prevent_pending_financial_document_journal_posting
before update of status on public.journal_entries
for each row
execute function private.prevent_pending_financial_document_journal_posting();

revoke all on function private.prevent_pending_financial_document_journal_posting()
from public, anon, authenticated, service_role;`);

  return preamble + bodies.join("\n\n") + "\n\ncommit;\n";
}

export async function loadRecoveredMigrations(directory = ARCHIVE_DIR) {
  const names = (await readdir(directory))
    .filter((name) => /^\d{14}_scms_\d{3}_.+\.sql$/i.test(name))
    .sort((a, b) => a.localeCompare(b));

  return Promise.all(names.map(async (name) => ({
    name,
    content: await readFile(path.join(directory, name), "utf8")
  })));
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const migrations = await loadRecoveredMigrations();
  const sql = composeBaseline(migrations);

  await mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  if (args.has("--check")) {
    const current = await readFile(OUTPUT_FILE, "utf8").catch(() => null);
    if (current !== sql) {
      console.error("Fresh-install baseline is missing or stale. Run: bun scripts/build-supabase-baseline.mjs");
      process.exitCode = 1;
      return;
    }
    console.log(`Baseline is current (${migrations.length} migrations, ${sql.length.toLocaleString()} characters).`);
    return;
  }

  await writeFile(OUTPUT_FILE, sql, "utf8");
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_FILE)} from ${migrations.length} recovered migrations (${sql.length.toLocaleString()} characters).`);
  console.log("This output is inactive and must be replay-tested on a disposable Supabase project before deployment.");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
